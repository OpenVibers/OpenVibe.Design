function byArea() {
    return AREAS.map((a) => ({ ...a, rules: RULES.filter((r) => r.area === a.id) })).filter((a) => a.rules.length);
}
function latest() {
    return RULES.map((r) => r.decided).sort().pop() || null;
}

module.exports = { AREAS, RULES, byArea, latest };
