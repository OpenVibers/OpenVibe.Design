/**
 * The decision register: every style, design and organization rule OpenVibe follows, in one place, with the day it
 * was decided, why, where it applies, what carries it out (a pattern, a kit part, a library) and what checks it.
 * openvibe.design/rules renders it; /api/v1/rules and /rules.md serve it as data.
 *
 * A rule is one sentence a person can act on. `why` says what went wrong, or what the rule protects, in a line.
 * `see` links to the pattern or part that implements it; `checked` names the test or tool that catches a breach.
 * Add a rule when a decision is made; change `decided` when it is revised, and say what changed in `why`.
 */

